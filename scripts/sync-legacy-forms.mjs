/**
 * Imports the designer's standalone form prototypes from data/ into the Vue app.
 *
 *   npm run legacy:sync
 *
 * For each form it writes resources/js/legacy/<name>/{markup.html,style.css,script.js}:
 *  - markup.html  the <body> markup, minus the inline <script>; logos point at /images
 *  - style.css    the stylesheet minus the font @import (fonts load once in app.blade.php);
 *                 it is scoped to the page wrapper at build time (see vite.config.js)
 *  - script.js    the prototype script wrapped as `mount(ctx)`, with submit wired to the server
 *
 * Every patch must match exactly once, so a design change that moves a hook fails
 * loudly here instead of silently breaking submission.
 */
import { mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const data = (file) => readFileSync(join(root, 'data', file), 'utf8');
const LOGO = '/images/ivauto-logo.png';

function replaceOnce(source, search, replacement, label) {
    const count = source.split(search).length - 1;
    if (count !== 1) {
        throw new Error(`[${label}] expected exactly 1 match for ${JSON.stringify(search.slice(0, 80))}, found ${count}`);
    }
    return source.replace(search, () => replacement);
}

function extractMarkup(html, label) {
    const start = html.indexOf('<body>');
    const end = html.lastIndexOf('<script>');
    if (start < 0 || end < start) throw new Error(`[${label}] could not find <body> … <script>`);
    return (
        html
            .slice(start + '<body>'.length, end)
            .replace(/data:image\/png;base64,[A-Za-z0-9+/=]+/g, LOGO)
            .trim() + '\n'
    );
}

function stripFontImport(css) {
    return css.replace(/@import url\([^)]*\);?/g, '').trim() + '\n';
}

function wrapScript(body, exportsExpr) {
    return `// GENERATED by scripts/sync-legacy-forms.mjs from data/ — do not edit by hand.
/* eslint-disable */
export function mount(ctx) {
${body.trim()}
return ${exportsExpr};
}
`;
}

const forms = [
    {
        name: 'assignment',
        html: 'IV_Auto_Assignment_Keys.html',
        css: 'assignment.css',
        js: 'assignment.js',
        markup(markup) {
            // The prototype persisted these files only in the browser; they are now uploaded to the server as they are added.
            return markup.replace(/<p class="pickup-documents-note">[\s\S]*?<\/p>\n?/, '');
        },
        script(js) {
            const label = 'assignment.js';
            // Submit goes to the server; the confirmation opens with the real stock number.
            js = replaceOnce(
                js,
                "status.style.display='none';openAssignmentConfirmation()}",
                "status.style.display='none';ctx.submit()}",
                label,
            );
            // Initial type comes from the page (?type=transport) instead of being hard-coded.
            js = replaceOnce(js, "setAssignmentType('Standard');", 'setAssignmentType(ctx.initialType);', label);
            // Start uploading each file the moment it is picked, restored or dropped, not at submit.
            js = replaceOnce(
                js,
                'selectedImages.push({file,url:URL.createObjectURL(file)})',
                "(selectedImages.push({file,url:URL.createObjectURL(file)}),ctx.fileAdded(file,'vehicle_image'))",
                label,
            );
            js = replaceOnce(
                js,
                'if(!existing)pickupDocumentFiles.push(item);',
                "if(!existing){pickupDocumentFiles.push(item);ctx.fileAdded(file,'pickup_document')}",
                label,
            );
            js = replaceOnce(
                js,
                'pickupDocumentFiles=stored.map(item=>({...item,saved:true}));',
                "pickupDocumentFiles=stored.map(item=>({...item,saved:true}));pickupDocumentFiles.forEach(item=>ctx.fileAdded(item.file,'pickup_document'));",
                label,
            );
            return wrapScript(js, '{ getPayload: getAssignmentPayload, openConfirmation: openAssignmentConfirmation }');
        },
    },
    {
        name: 'bid',
        html: 'IV_Auto_Bid_Profile_Formatting.html',
        css: 'bid.css',
        js: 'bid.js',
        markup: (markup) => markup,
        script(js) {
            const label = 'bid.js';
            js = replaceOnce(
                js,
                "$('submitResult').style.display='none';openBidConfirmation()};",
                "$('submitResult').style.display='none';ctx.submit()};",
                label,
            );
            // Start uploading each file the moment it is added, not at submit.
            js = replaceOnce(
                js,
                'state[kind].push(file);',
                "state[kind].push(file);ctx.fileAdded(file,kind==='images'?'vehicle_image':'bid_document');",
                label,
            );
            // The prototype has no payload builder; it needs `state` and `documentKinds`, which are local to it.
            js += `
function getBidPayload(){const fields={};document.querySelectorAll('#bidForm input[id],#bidForm select[id],#bidForm textarea[id]').forEach(control=>{if(control.type==='file')return;fields[control.id]=control.type==='checkbox'?control.checked:control.value.trim()});return {fields,noImages:$('noImages').checked,noDocuments:$('noDocuments').checked,images:[...state.images],documents:[...state.documents],documentDetails:state.documents.map(file=>({name:file.name,documentType:documentKinds.get(documentKey(file))||null}))}}
`;
            return wrapScript(js, '{ getPayload: getBidPayload, openConfirmation: openBidConfirmation }');
        },
    },
];

for (const form of forms) {
    const out = join(root, 'resources/js/legacy', form.name);
    mkdirSync(out, { recursive: true });
    writeFileSync(join(out, 'markup.html'), form.markup(extractMarkup(data(form.html), form.html)));
    writeFileSync(join(out, 'style.css'), stripFontImport(data(form.css)));
    writeFileSync(join(out, 'script.js'), form.script(data(form.js)));
    console.log(`synced ${form.name} -> resources/js/legacy/${form.name}`);
}

// One shared logo file instead of ~17 KB of base64 repeated in every page.
const logo = data('index.html').match(/data:image\/png;base64,([A-Za-z0-9+/=]+)/);
if (!logo) throw new Error('logo not found in data/index.html');
mkdirSync(join(root, 'public/images'), { recursive: true });
writeFileSync(join(root, 'public/images/ivauto-logo.png'), Buffer.from(logo[1], 'base64'));
console.log('wrote public/images/ivauto-logo.png');
